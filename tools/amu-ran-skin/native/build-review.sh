#!/bin/zsh
set -euo pipefail
AMU_REPO="${0:A:h:h:h:h}"
AMU_REVIEW_ROOT="$(mktemp -d /private/tmp/retto-amu-review.XXXXXX)"
AMU_APP="$AMU_REVIEW_ROOT/AmuReview.app"
AMU_CONTENTS="$AMU_APP/Contents"
mkdir -p "$AMU_CONTENTS/MacOS" "$AMU_CONTENTS/Resources"
cp -R "$AMU_REPO/macos/Sources" "$AMU_REVIEW_ROOT/Sources"
swiftc -O -module-cache-path "$AMU_REVIEW_ROOT/module-cache" -target arm64-apple-macos13.0 -framework AppKit -framework ServiceManagement "$AMU_REVIEW_ROOT"/Sources/*.swift -o "$AMU_CONTENTS/MacOS/Retto"
cp "$AMU_REPO/macos/Info.plist" "$AMU_CONTENTS/Info.plist"
cp "$AMU_REPO/assets/spritesheet.webp" "$AMU_REPO/assets/spritesheet-amu-ran.webp" "$AMU_REPO/assets/NanumMiNiSonGeurSsi.ttf" "$AMU_CONTENTS/Resources/"
cp "$AMU_REPO/assets/christmas-16-timing.json" "$AMU_REPO/assets/christmas-16-attachments.json" "$AMU_REPO/assets/spritesheet-christmas-16-character.webp" "$AMU_CONTENTS/Resources/"
cp -R "$AMU_REPO/assets/amu-ran-frames" "$AMU_CONTENTS/Resources/AmuRanFrames"
codesign --force --deep --sign - "$AMU_APP"
"$AMU_CONTENTS/MacOS/Retto" --self-test > "$AMU_REVIEW_ROOT/self-test.log"
"$AMU_CONTENTS/MacOS/Retto" --self-test-amu-ran-clock > "$AMU_REVIEW_ROOT/clock-test.log"
"$AMU_CONTENTS/MacOS/Retto" --render-amu-ran-motion-preview "$AMU_REVIEW_ROOT/motion" > "$AMU_REVIEW_ROOT/motion-test.log"
"$AMU_CONTENTS/MacOS/Retto" --render-amu-ran-gaze-preview "$AMU_REVIEW_ROOT/gaze" > "$AMU_REVIEW_ROOT/gaze-test.log"
codesign --verify --deep --strict "$AMU_APP"
print -r -- "$AMU_REVIEW_ROOT"
